-- Effective plan: paid/comped plan, raised to Growth while enrolled in a Road to Funding cohort (§4D perk).
create or replace function public.fl_my_plan() returns text
language sql stable security definer set search_path = public as $$
  with paid as (
    select case when s.status in ('active', 'trialing', 'past_due') then s.plan else 'free' end as plan
    from public.subscriptions s where s.user_id = auth.uid()
  ), cohort as (
    select 'growth'::text as plan from public.cohort_enrollments e join public.cohorts c on c.id = e.cohort_id
    where e.user_id = auth.uid() and e.status = 'enrolled' and current_date <= c.end_date
  ), ranked as (
    select plan, array_position(array['free', 'starter', 'growth', 'pro'], plan) as r from paid
    union all select plan, array_position(array['free', 'starter', 'growth', 'pro'], plan) from cohort
    union all select 'pro', 4 where public.is_admin()
    union all select 'free', 1
  )
  select plan from ranked order by r desc limit 1;
$$;
grant execute on function public.fl_my_plan() to authenticated;

