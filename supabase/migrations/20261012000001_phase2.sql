-- Status side effects: timestamps, and on Approved a funding_history row + standard obligations (once).
create or replace function public.fl_application_status() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  v_level text;
  v_funder text;
  v_source public.funding_source;
  v_amount numeric;
  v_fh uuid;
  d date := current_date;
begin
  -- The funding_history link is set only here, never by the client.
  if tg_op = 'INSERT' then new.funding_history_id := null; else new.funding_history_id := old.funding_history_id; end if;
  if tg_op = 'UPDATE' and new.status is not distinct from old.status then return new; end if;
  if new.status = 'submitted' and new.submitted_at is null then new.submitted_at := now(); end if;
  if new.status in ('approved', 'declined') then new.decision_at := coalesce(new.decision_at, now()); end if;
  if new.status not in ('approved', 'declined') then new.decision_at := null; end if;

  if new.status = 'approved' and new.funding_history_id is null then
    select level, funder into v_level, v_funder from public.programs where id = new.program_id;
    v_source := case new.type
      when 'grant' then (case when coalesce(v_level, 'federal') = 'federal' then 'grant_federal' else 'grant_provincial' end)::public.funding_source
      when 'loan' then 'business_loan'::public.funding_source
      when 'crowdfunding' then 'crowdfunding'::public.funding_source
      else coalesce(new.funding_source, 'angel'::public.funding_source) end;
    v_amount := coalesce(new.amount_approved, new.amount_requested, 0);
    insert into public.funding_history (business_id, source, amount, year, program_name, provider_name, status)
    values (new.business_id, v_source, v_amount, extract(year from d)::smallint,
            new.title, coalesce(new.provider, v_funder), 'active')
    returning id into v_fh;
    new.funding_history_id := v_fh;
    new.amount_approved := v_amount;

    -- Obligations are inserted after the row exists (see fl_application_obligations).
  end if;
  return new;
end $$;
create trigger applications_status before insert or update on public.applications
  for each row execute function public.fl_application_status();

create or replace function public.fl_application_obligations() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  d date := current_date;
begin
  if new.status <> 'approved' or new.funding_history_id is null then return new; end if;
  if tg_op = 'UPDATE' and old.funding_history_id is not distinct from new.funding_history_id then return new; end if;
  if exists (select 1 from public.obligations where application_id = new.id) then return new; end if;
  insert into public.obligations (business_id, application_id, funding_history_id, type, title, due_date, recurrence)
  select new.business_id, new.id, new.funding_history_id, o.type, o.title, o.due, o.rec
  from (values
    -- grants and contributions: claims, interim and final reports
    ('grant', 'claim', 'First expense claim: ' || new.title, d + 90, 'quarterly'),
    ('grant', 'report', 'Interim progress report: ' || new.title, d + 182, null),
    ('grant', 'report', 'Final report: ' || new.title, d + 365, null),
    -- loans: payments and annual covenant review
    ('loan', 'payment', 'Loan payment: ' || new.title, d + 30, 'monthly'),
    ('loan', 'covenant', 'Annual covenant / financial statements to lender: ' || new.title, d + 365, 'annually'),
    -- equity: investor updates
    ('investor', 'investor_update', 'Investor update: ' || new.title, d + 90, 'quarterly'),
    ('crowdfunding', 'report', 'Backer / investor update: ' || new.title, d + 90, 'quarterly')
  ) as o(app_type, type, title, due, rec)
  where o.app_type = new.type;
  return new;
end $$;
create trigger applications_obligations after insert or update on public.applications
  for each row execute function public.fl_application_obligations();

