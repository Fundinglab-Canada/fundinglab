-- Viewer opens the room with their token. Returns {status: ok|invalid|expired, room?, documents?}.
-- Only the latest version of each document, never storage paths.
create or replace function public.fl_data_room_open(p_token text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  a public.data_room_access;
  v_docs jsonb;
  v_name text;
  v_wm boolean;
begin
  select * into a from public.data_room_access where token = p_token and revoked_at is null;
  if not found then return jsonb_build_object('status', 'invalid'); end if;
  if a.expires_at < now() then return jsonb_build_object('status', 'expired'); end if;
  update public.data_room_access set last_viewed_at = now() where id = a.id;
  select b.name, coalesce(r.watermark_enabled, true) into v_name, v_wm
    from public.businesses b left join public.data_rooms r on r.business_id = b.id where b.id = a.business_id;
  select coalesce(jsonb_agg(jsonb_build_object(
           'id', d.id, 'folder', d.folder, 'file_name', d.file_name, 'mime_type', d.mime_type,
           'size_bytes', d.size_bytes, 'version', d.version, 'created_at', d.created_at)
         order by d.folder, d.file_name), '[]'::jsonb)
    into v_docs
  from public.documents d
  where d.business_id = a.business_id and d.in_data_room
    and not exists (select 1 from public.documents n where n.previous_id = d.id);
  return jsonb_build_object('status', 'ok', 'business_name', v_name, 'email', a.email, 'expires_at', a.expires_at,
                            'can_download', a.can_download, 'watermark', v_wm, 'documents', v_docs);
end $$;
revoke all on function public.fl_data_room_open(text) from public;
grant execute on function public.fl_data_room_open(text) to anon, authenticated;

-- Authorizes one file for a viewer and logs the view. Returns the storage path only to the trusted
-- server route (called with the service role), which streams the file; anon cannot call it.
create or replace function public.fl_data_room_file(p_token text, p_document uuid, p_action text)
returns table (storage_path text, file_name text, mime_type text, viewer_email text, watermark boolean)
language plpgsql security definer set search_path = public as $$
declare
  a public.data_room_access;
begin
  if p_action not in ('view', 'download') then raise exception 'Invalid action'; end if;
  select * into a from public.data_room_access x where x.token = p_token and x.revoked_at is null and x.expires_at > now();
  if not found then return; end if;
  if p_action = 'download' and not a.can_download then return; end if;
  if not exists (select 1 from public.documents d where d.id = p_document and d.business_id = a.business_id and d.in_data_room) then return; end if;
  insert into public.document_views (access_id, document_id, viewer_email, action) values (a.id, p_document, a.email, p_action);
  return query
  select d.storage_path, d.file_name, d.mime_type, a.email, coalesce(r.watermark_enabled, true)
  from public.documents d left join public.data_rooms r on r.business_id = d.business_id
  where d.id = p_document;
end $$;
revoke all on function public.fl_data_room_file(text, uuid, text) from public, anon, authenticated;

